  let currentLang = localStorage.getItem('cakra_lang') || 'en';

  // t('some.key', { n: 5, pct: '12.3' }) → mengganti token {n}, {pct}, dst di dalam string dictionary.
  function t(key, params) {
    let str = (DICT[currentLang] && DICT[currentLang][key]) || (DICT.en[key]) || (DICT.id[key]) || key;
    if (params) {
      Object.keys(params).forEach(k => {
        str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), params[k]);
      });
    }
    return str;
  }

  function apply() {
    document.documentElement.setAttribute('lang', currentLang);
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      el.textContent = t(key);
    });
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      el.innerHTML = t(key);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      el.setAttribute('placeholder', t(key));
    });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      el.setAttribute('title', t(key));
    });
    const btnId = document.getElementById('langBtnId');
    const btnEn = document.getElementById('langBtnEn');
    if (btnId) btnId.classList.toggle('active', currentLang === 'id');
    if (btnEn) btnEn.classList.toggle('active', currentLang === 'en');
    // Render ulang konten dinamis (tabel, KPI, dsb) di dashboard.js kalau tersedia.
    if (typeof window.CakraRebuildDynamic === 'function') window.CakraRebuildDynamic();
  }

  function setLanguage(lang) {
    if (!DICT[lang]) return;
    currentLang = lang;
    localStorage.setItem('cakra_lang', lang);
    apply();
  }

  document.addEventListener('DOMContentLoaded', apply);

  return { setLanguage, t, get currentLang() { return currentLang; } };
